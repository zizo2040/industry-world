// دالة مساعدة: تقرأ من DB أولاً ثم env ثم الافتراضي
function ai_cfg(string $dbKey, string $envKey, string $default = ''): string {
    static $cache = [];
    if (isset($cache[$dbKey])) return $cache[$dbKey];

    // من قاعدة البيانات
    if (function_exists('getSetting')) {
        $dbVal = getSetting($dbKey);
        if ($dbVal !== null && $dbVal !== '') {
            return $cache[$dbKey] = $dbVal;
        }
    }

    // من متغيرات البيئة
    $envVal = getenv($envKey);
    if ($envVal !== false && $envVal !== '') {
        return $cache[$dbKey] = $envVal;
    }

    return $cache[$dbKey] = $default;
}

